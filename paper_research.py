"""
Figure 4: Confusion Matrix for Attack Classification
Publication-Ready for Q1 Journal
"""

import numpy as np
import matplotlib.pyplot as plt

plt.rcParams['figure.dpi'] = 300
plt.rcParams['savefig.dpi'] = 300
plt.rcParams['font.size'] = 11
plt.rcParams['font.family'] = 'serif'
plt.rcParams['font.serif'] = ['Times New Roman']

def create_figure4():
    attack_types = ['Direct\nInjection', 'Indirect\nInjection', 'Jailbreak',
                    'Tool\nManipulation', 'Context\nPoisoning', 'Multi-Step', 'Benign']

    # Confusion matrix (actual vs predicted)
    cm = np.array([
        [187, 8, 3, 2, 0, 0, 0],     # Direct Injection
        [6, 172, 12, 4, 3, 3, 0],    # Indirect Injection
        [4, 10, 178, 5, 2, 1, 0],    # Jailbreak
        [2, 5, 6, 179, 5, 3, 0],     # Tool Manipulation
        [1, 4, 3, 6, 165, 8, 13],    # Context Poisoning
        [0, 3, 2, 4, 7, 175, 9],     # Multi-Step
        [0, 0, 0, 0, 12, 10, 178]    # Benign
    ])

    # Normalize row-wise
    cm_normalized = cm.astype('float') / cm.sum(axis=1)[:, np.newaxis] * 100

    fig, ax = plt.subplots(1, 1, figsize=(11, 9))

    # Create heatmap
    im = ax.imshow(cm_normalized, cmap='RdYlGn', aspect='auto', vmin=0, vmax=100)

    # Colorbar
    cbar = plt.colorbar(im, ax=ax, shrink=0.8)
    cbar.set_label('Classification Rate (%)', fontsize=12, fontweight='bold')

    # Set ticks
    ax.set_xticks(np.arange(len(attack_types)))
    ax.set_yticks(np.arange(len(attack_types)))
    ax.set_xticklabels(attack_types, fontsize=10)
    ax.set_yticklabels(attack_types, fontsize=10)

    # Labels
    ax.set_xlabel('Predicted Attack Type', fontsize=13, fontweight='bold')
    ax.set_ylabel('Actual Attack Type', fontsize=13, fontweight='bold')
    ax.set_title('Confusion Matrix: Multi-Class Attack Classification Results',
                fontsize=14, fontweight='bold', pad=20)

    # Add text annotations
    for i in range(len(attack_types)):
        for j in range(len(attack_types)):
            if cm[i, j] > 0:
                text_color = 'white' if cm_normalized[i, j] < 85 else 'black'
                ax.text(j, i, f'{cm[i, j]}\n({cm_normalized[i, j]:.1f}%)',
                       ha='center', va='center', fontsize=8,
                       fontweight='bold' if i == j else 'normal',
                       color=text_color)

    # Calculate metrics
    total_correct = np.trace(cm)
    total_samples = np.sum(cm)
    accuracy = total_correct / total_samples * 100
    precision = np.mean([cm[i,i]/cm[:,i].sum() for i in range(len(attack_types)) if cm[:,i].sum() > 0])
    recall = np.mean([cm[i,i]/cm[i,:].sum() for i in range(len(attack_types)) if cm[i,:].sum() > 0])

    # Add metrics box
    textstr = f'Overall Accuracy: {accuracy:.1f}%\nMean Precision: {precision:.3f}\nMean Recall: {recall:.3f}'
    props = dict(boxstyle='round', facecolor='wheat', alpha=0.9)
    ax.text(1.02, 0.98, textstr, transform=ax.transAxes, fontsize=10,
            verticalalignment='top', bbox=props)

    plt.tight_layout()
    plt.savefig('Figure4_Confusion_Matrix.pdf', format='pdf', bbox_inches='tight')
    plt.savefig('Figure4_Confusion_Matrix.png', format='png', bbox_inches='tight', dpi=300)
    plt.show()
    print("✓ Figure 4 saved: Figure4_Confusion_Matrix.pdf/png")

if __name__ == "__main__":
    create_figure4()

