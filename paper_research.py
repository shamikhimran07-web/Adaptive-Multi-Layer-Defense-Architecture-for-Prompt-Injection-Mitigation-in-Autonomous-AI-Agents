class InputSanitizationLayer:

    def process(self, prompt):
        suspicious_terms = [
            "ignore previous instructions",
            "developer mode",
            "bypass safety",
            "system prompt"
        ]

        risk = sum(
            1 for term in suspicious_terms
            if term.lower() in prompt.lower()
        )

        return {
            "sanitized_prompt": prompt,
            "risk_score": risk
        }


class ContextualValidationLayer:

    def validate(self, prompt):
        score = 0.90

        if "ignore" in prompt.lower():
            score -= 0.25

        return score


class BehavioralAnomalyLayer:

    def compute_anomaly(self, actions):

        if len(actions) == 0:
            return 0

        return min(len(actions) / 20.0, 1.0)


class TrustController:

    def calculate_trust(
        self,
        contextual_score,
        behavioral_score,
        historical_score
    ):
        alpha = 0.4
        beta = 0.3
        gamma = 0.3

        return (
            alpha * contextual_score +
            beta * (1 - behavioral_score) +
            gamma * historical_score
        )


class AdaptiveMonitoring:

    def monitor(self, trust_score):

        if trust_score > 0.8:
            return "ALLOW"

        elif trust_score > 0.5:
            return "SANDBOX"

        return "BLOCK"


# ============================================================
# DEMONSTRATION PIPELINE
# ============================================================

def framework_demo(prompt):

    sanitizer = InputSanitizationLayer()
    validator = ContextualValidationLayer()
    anomaly = BehavioralAnomalyLayer()
    trust = TrustController()
    monitor = AdaptiveMonitoring()

    result = sanitizer.process(prompt)

    contextual_score = validator.validate(prompt)

    anomaly_score = anomaly.compute_anomaly(
        ["tool_call", "api_access"]
    )

    trust_score = trust.calculate_trust(
        contextual_score,
        anomaly_score,
        0.9
    )

    decision = monitor.monitor(trust_score)

    return {
        "trust_score": trust_score,
        "decision": decision
    }

